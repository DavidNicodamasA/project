export const seedDatabase = async () => {
  try {
    // Ensure default mock providers are removed so only registered providers exist
    await Provider.deleteMany({
      $or: [
        { id: { $in: ['prov-1', 'prov-2', 'prov-3', 'prov-4', 'prov-5', 'prov-6', 'prov-7'] } },
        { email: { $regex: /@handypro\.com$/i } },
      ],
    });
    console.log('[MongoDB Seed] Mock providers removed; only registered providers kept.');

    const bookingCount = await Booking.countDocuments();
    if (bookingCount === 0) {
      await Booking.insertMany(INITIAL_BOOKINGS);
      console.log(`[MongoDB Seed] Inserted ${INITIAL_BOOKINGS.length} initial bookings.`);
    }

    // Clean up any legacy demo sample users from the User collection
    await User.deleteMany({
      $or: [
        { id: { $in: ['cust-demo-1', 'prov-1', 'prov-2', 'prov-3', 'prov-4', 'prov-5', 'prov-6', 'prov-7'] } },
        { email: { $regex: /@handypro\.com$/i } },
      ],
    });
    console.log('[MongoDB Seed] Sample demo users removed from users collection.');
  } catch (error) {
    console.error(`[MongoDB Seed Error]: ${error.message}`);
  }
};

export default seedDatabase;

